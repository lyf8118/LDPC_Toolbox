        8   50   89  131; 0   49  115  151; 38  80  109  147; 37  54  122  159; ...
        32  79   97  120; 24  69  102  133; 7   45  107  145; 16  58   94  139; ...
        25  70  103  134; 28  73  101  154; 30  80   98  121; 13  55   90  136; ...
        29  74   99  155; 19  76   87  157; 39  66  117  151; 7   49   88  130; ...
        23  76  105  141; 37  79  108  149; 31  78   96  122; 4   46   85  127; ...
        27  72  100  153; 34  74  111  157; 6   47  106  144; 9   60   96  141; ...
        3   65  104  149; 35  72  112  158; 1   50  116  152; 34  51   83  138; ...
        20  68  110  131; 32  41   95  153; 4   63  102  147; 41  68  119  150; ...
        31  40   94  155; 5   64  103  148; 15  65  116  123; 11  62   98  143; ...
        17  64  115  125; 12  54   92  135; 26  59  118  137; 2   44   83  125; ...
        21  62  111  127; 29  70   84  160; 12  44  100  145; 33  53   82  140; ...
        1   43   82  124; 5   47   86  128; 15  57   93  138; 24  57  119  135; ...
        14  43   99  144; 2   48  114  150; 14  56   91  137; 6   48   87  129; ...
        35  52   81  139; 10  61   97  142; 18  75   89  156; 11  53   92  134; ...
        9   51   90  132
    ];

    % GF Element Values
    hElementsRaw = [
        46    45     44     15;  58    56     60     62;  54     7     38     23;  26    22     14      2; ...
        35     1     31     44;  16    63     20     9;  42    47     37      32;  63    13     54     10; ...
        1     21     25      7;  41    48      2     27;  46    25     22     48;  60    24      4     50; ...
        25    11      7      1;  13    27     56      8;  60    48      2     27;  53    35     16     13; ...
        20    16     63      9;  43    47     18     20;   9    41     57     58;  37    53     61     29; ...
        19    24     42     14;  15    24     50     37;  37    53     61     29;  51    59     63     47; ...
        63    26     41     12;  44    51     35     13;  27    56      8     43;  38    12     25     51; ...
        2     46     56     35;  43    58     19     49;  49    21      7     35;  13    29     53     61; ...
        32    49     58     19;  32    49     58     19;  53    40     61     18;  50    54     60     62; ...
        23    25     30     16;  27    37      5     26;  42    14     24     33;   5    31     51     30; ...
        6     45     56     19;   1    45     15      6;  24    50     37     15;  46    58     18      6; ...
        9      3     43     29;  17    32     58     37;  30     1     44      7;   1    44     30     24; ...
        43    34     48     57;  47    20     33     26;  28     4     52     44;  40    21     44     17; ...
        52    17     24     61;  43    34     48     57;  42    14     24     33;   8    43     27     56; ...
        58    19     32     49;  18     6     61     21;  29     7     10     16;  43    22     41     20; ...
        9      3     63     43;  33    45     36     34;   8    43     27     56;  15    32     18     61; ...
        36    19      3     57;  56     8     46     13;  38    23     55     22;  27     5      2     62; ...
        5     26     27     37;  39     9     30     48;  62    54     56     60;  46    44     14     15; ...
