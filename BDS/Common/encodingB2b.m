    %%  Matrix Reconstruction =============================================
    % Convert 0-based indices to 1-based (MATLAB standard)
    hIndices = hIndicesRaw + 1;
    
    % Initialize 81x162 Parity Check Matrix H (Sparse representation in Dense format)
    hMatrix = zeros(81, 162);
    
    % Populate H Matrix
    [rows, cols] = size(hIndices);
    for i = 1:rows
        for j = 1:cols
            colIndex = hIndices(i, j);
            elementVal = hElementsRaw(i, j);
            hMatrix(i, colIndex) = elementVal;
        end
    end
    
    % Convert to Galois Field Object
    hMatrixGf = gf(hMatrix, gfBits);
    
    %%  Encoding Calculation ==============================================
    % H = [H1 | H2]
    h1 = hMatrixGf(:, 1:81);     % Information part connection
    h2 = hMatrixGf(:, 82:162);   % Parity part connection (Square, Invertible)
    
    % Compute Parity Generator Part: G2 = (H2^-1 * H1)^T
    % P = u * G2
    g2 = (h2 \ h1).'; 
    
    % Convert input to GF
    infoSeqGf = gf(infoSymbols, gfBits);
    
    % Calculate Parity Symbols
    paritySeqGf = infoSeqGf * g2;
    
    % Concatenate to form full codeword: [Info, Parity]
    codewordGf = [infoSeqGf, paritySeqGf];
    
    %%  Output Formatting (Vectorized) ====================================
    % Extract Decimal Values
    numericCodeword = double(codewordGf.x); % [1 x 162]

    %  Vectorized conversion from Decimal to Binary Matrix
    % Transpose to column vector [162 x 1] for dec2bin
    % dec2bin produces char matrix [162 x 6]
    % Subtracting '0' converts char '0'/'1' to double 0/1
    binaryCodeword = dec2bin(numericCodeword.', gfBits) - '0';
    
    % Output format: [162 x 6] (Rows=Symbols, Cols=Bits)
    
end