function binaryCodeword = encodingB2b(infoSymbols)
% =========================================================================
% FUNCTION: encodingB2b
% DESCRIPTION:
%   Performs Non-Binary LDPC encoding for the B2b GNSS signal.
%   Constructs the systematic codeword from the provided sparse Parity 
%   Check Matrix (H).
%
%   Systematic Encoding Strategy:
%   H = [H1 | H2], where H2 is square (81x81) and invertible.
%   Codeword C = [Information (u) | Parity (p)]
%   Constraint: H * C^T = 0  => H1*u^T + H2*p^T = 0
%   Solution:   p = u * (H2^-1 * H1)^T
%
% INPUTS:
%   infoSymbols     : [1 x 81] Array of information symbols (decimal).
%
% OUTPUTS:
%   binaryCodeword  : [162 x 6] Binary matrix (Rows = Symbols, Cols = Bits).
%  
% =========================================================================

    %%  Configuration & Data Definition ===================================
    gfBits = 6;      % GF(2^6)
    
    % Raw Column Indices (0-based from spec)
    hIndicesRaw = [
        19  67  109  130; 26  71  104  132; 13  42  101  146; 23  61  113  126; ...
        22  60  112  128; 3   45   84  126; 20  77   88  158; 0   42   81  123; ...
